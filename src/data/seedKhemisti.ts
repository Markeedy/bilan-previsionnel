export function computeBudgetItem(raw: typeof RAW_ITEMS_DATA[0]): BudgetItem {
  const remainingQuantity = Number((raw.contractQuantity - raw.previousQuantity).toFixed(3));
  const contractAmount = Number((raw.contractQuantity * raw.unitPrice).toFixed(2));
  const previousAmount = Number((raw.previousQuantity * raw.unitPrice).toFixed(2));
  const remainingAmount = Number((remainingQuantity * raw.unitPrice).toFixed(2));

  const forecastAmounts: Record<string, number> = {};
  for (const [month, qty] of Object.entries(raw.forecasts)) {
    forecastAmounts[month] = Number((qty * raw.unitPrice).toFixed(2));
  }

  return {
    ...raw,
    remainingQuantity,
    contractAmount,
    previousAmount,
    remainingAmount,
    forecastAmounts,
  };
}

export const INITIAL_BUDGET_ITEMS: BudgetItem[] = RAW_ITEMS_DATA.map(computeBudgetItem);
